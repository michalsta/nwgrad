#!/usr/bin/env python3
"""Generate the GNU ld code-layout fragments (see their headers and AGENTS.md "Code placement").

    python tools/gen_text_ld.py units  > src/nwgrad/cpp/nwgrad/nwgrad_text.ld          (the default)
    python tools/gen_text_ld.py groups > src/nwgrad/cpp/nwgrad/nwgrad_text_groups.ld   (-DNWGRAD_KERNEL_LAYOUT=groups)

units:  every translation unit's functions in their own block, the block starting at a FIXED offset within
        a 4 KiB page: the offset each unit had in main df4ae0a's own link (UNIT_OFFSET below).  Inside a
        unit the order is the compiler's, as before, so at adoption every function of these units sits at
        exactly main's address mod 4096; afterwards a change in one unit no longer moves any other.
groups: finer: the engine code of each (scalar type, gap model, mode), the bindings' std:: code, the rest of
        the bindings, and each level unit's kernels of one scalar type, each group on its own page
        boundary (GROUP_OFFSET where measured).  Protects against more (a change in the bindings no longer
        moves the engines), but it is a different layout from main's: measured on nighthaven it loses
        2-8 % on some cells (AGENTS.md).
Matching is on -ffunction-sections names (.text._Z<mangled>); the cold splits (.text.unlikely.*), static
constructors and the runtime/library objects stay in .text.  A function matched twice goes to the first.
"""
import sys

# Offset of each unit's first function mod 4096 in main df4ae0a (release-wheel flags, gcc 16.2.1, ld 2.47,
# nighthaven's toolchain; read from the link map, unit order as on the link line).
UNIT_OFFSET = [("py_exports", 0), ("level_baseline", 192), ("level_sse4", 3712), ("level_avx2", 640),
               ("level_avx512", 3584), ("level_baseline_soft", 1760), ("level_sse4_soft", 4032),
               ("level_avx2_soft", 2080), ("level_avx512_soft", 2048), ("level_baseline_inter", 2080),
               ("level_sse4_inter", 160), ("level_avx2_inter", 2144), ("level_avx512_inter", 1376),
               # AArch64 (no measured offsets: page-aligned)
               ("level_neon", 0), ("level_neon_soft", 0), ("level_neon_inter", 0)]

TYPES = ["f", "d", "s", "i", "l"]                 # float, double, int16, int32, int64 (Itanium codes)
LEVELS = ["avx2", "avx512", "sse4", "baseline", "neon"]
UNITS = ["_inter", "", "_soft"]
# The avx2 inter-pair float32 group (nighthaven, the group shifted 0..3712 with everything else fixed,
# protein L100, 1 / 6 threads): float32 Global hard 1.12 / 1.11 at 0 and 1.14 / 1.10 at 2048 against
# main; at 3712 1.017 / 1.004, Local path 1.009 / 0.995, Local hard 1.002, protein L300 path 1.007-1.008.
GROUP_OFFSET = {("avx2", "_inter", "f"): 3712}

HEAD = """/* Code layout for GNU ld (ELF), passed with -Wl,-T: see "Code placement" in CMakeLists.txt and AGENTS.md.
   GENERATED by tools/gen_text_ld.py ({mode}) -- edit that, not this.  INSERT augments the default script.

   Why: on Alder Lake (nighthaven) a kernel's speed depends on its address mod 4 KiB relative to the
   engine code that drives it: moving the bindings 448 bytes against the kernels made float32 inter-pair
   cells up to 1.13x slower, with identical code.  With the default script each function's address was
   the size of everything linked before it, so a change anywhere moved every kernel after it.  Here
   each block below starts at a fixed offset within a page, so its code keeps its address mod 4096
   whatever the other blocks do.
   Cost: at most 4 KiB of padding per block.  The experiment knob's pads (placement_shift.cpp) go first
   and at the start of the bindings{grpnote}. */
SECTIONS
{{
  .text.nwgrad ALIGN(4096) :
  {{
    KEEP(*(.text.unlikely.nwgrad_placement_shift))"""
TAIL = """    . = ALIGN(4096);
  }
}
INSERT BEFORE .text;"""


def at(off):
    return f" . += {off};" if off else ""


def units():
    out = [HEAD.format(mode="units", grpnote="")]
    for u, off in UNIT_OFFSET:
        pat = ".text._Z* .text.Py*" if u == "py_exports" else ".text._Z*"
        knob = " KEEP(*(.text.nwgrad_placement_shift))" if u == "py_exports" else ""
        out.append(f"    . = ALIGN(4096);{at(off)}{knob} *{u}.cpp.o({pat})")
    out.append(TAIL)
    return out


def groups():
    out = [HEAD.format(mode="groups", grpnote=" / of the avx2 inter-pair float32 group")]
    for t in TYPES:
        for g in "01":
            for m in "012":
                out.append(f"    . = ALIGN(4096); *py_exports.cpp.o(.text._Z*BatchEngineI{t}L8GapModel{g}EL9AlignMode{m}E* "
                           f".text._Z*AlignerIL8GapModel{g}EL9AlignMode{m}EL9AlignBand?E{t}E*)")
    # the standard-library instantiations the engines call per pair (std::vector resize / assign / erase),
    # apart from the bindings, whose code changes most
    out.append("    . = ALIGN(4096); *py_exports.cpp.o(.text._ZNSt* .text._ZNKSt* .text._ZSt* .text._ZN9__gnu_cxx*)")
    out.append("    . = ALIGN(4096); KEEP(*(.text.nwgrad_placement_shift)) *py_exports.cpp.o(.text._Z* .text.Py*)")
    for lv in LEVELS:
        for u in UNITS:
            obj = f"*level_{lv}{u}.cpp.o"
            for t in TYPES:
                grp = "KEEP(*(.text.nwgrad_placement_shift_grp)) " if (lv, u, t) == ("avx2", "_inter", "f") else ""
                out.append(f"    . = ALIGN(4096);{at(GROUP_OFFSET.get((lv, u, t), 0))} {grp}{obj}(.text._Z*[a-z_]I{t}[LE]*)")
            out.append(f"    . = ALIGN(4096); {obj}(.text._Z*)")
    out.append(TAIL)
    return out


mode = sys.argv[1] if len(sys.argv) > 1 else "units"
print("\n".join({"units": units, "groups": groups}[mode]()))
