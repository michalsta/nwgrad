#!/usr/bin/env python3
"""Generate src/nwgrad/cpp/nwgrad/nwgrad_text.ld (the GNU ld code-layout fragment; see its header).

    python tools/gen_text_ld.py > src/nwgrad/cpp/nwgrad/nwgrad_text.ld

Groups, each starting on a 4 KiB boundary, in this order:
  1. per scalar type T, gap model G, mode M: the batch engine and aligner code of (T, G, M) from
     py_exports.cpp (BatchEngine<T,G,M>, Aligner<G,M,*,T>, and everything instantiated for them);
  2. py_exports.cpp's standard-library instantiations (std::vector etc.), then the rest of it;
  3. per per-ISA-level unit, per scalar type: that unit's kernels of type T; then the unit's rest.
Matching is on -ffunction-sections names (.text._Z<mangled>); .text.unlikely.* (cold splits) is not
matched and stays in .text.  A function matched by two groups goes to the first.
"""
TYPES = ["f", "d", "s", "i", "l"]                 # float, double, int16, int32, int64 (Itanium codes)
LEVELS = ["avx2", "avx512", "sse4", "baseline", "neon"]
UNITS = ["_inter", "", "_soft"]
# Offset of a group's start within its page, where measured to matter.  The avx2 inter-pair float32
# group (nighthaven, Alder Lake, the group shifted 0..3712 with everything else fixed, protein L100,
# 1 / 6 threads): float32 Global hard 1.12 / 1.11 at 0 and 1.14 / 1.10 at 2048, against main; at
# 3712: Global hard 1.017 / 1.004, Local path 1.009 / 0.995, Local hard 1.002, Global path 0.994,
# protein L300 path 1.007-1.008 (results/nighthaven.md, "Placement").
OFFSET = {("avx2", "_inter", "f"): 3712}

out = []
w = out.append
w("""/* Code layout for GNU ld (ELF), passed with -Wl,-T: see "Code placement" in CMakeLists.txt.
   GENERATED by tools/gen_text_ld.py -- edit that, not this.  INSERT augments the default script.

   Why: on Alder Lake (nighthaven) a kernel's speed depends on where it sits relative to the engine
   code that drives it (the batch loop, traceback walk and setup in py_exports.cpp) modulo 4 KiB:
   moving the level units against the bindings by 448 bytes made float32 inter-pair cells 1.07-1.13x
   slower, with byte-identical code, while moving the whole extension together changed nothing
   (results/nighthaven.md, "Placement").  With the default script every kernel's offset from its
   driver is the size of everything linked between them, so any unrelated change moved it.

   Here each group starts on a 4 KiB boundary: the batch engine + aligner code of one (scalar type,
   gap model, mode), the bindings' std:: instantiations (vector resize etc., called per pair), the
   rest of the bindings, and each level unit's kernels of one scalar type.  A
   kernel's offset from its driver mod 4096 then depends only on the code in its own two groups.
   Cost: at most 4 KiB of padding per group (~120 groups, ~0.25 MB).  The experiment knob's pads
   (placement_shift.cpp) are placed first / at the start of the avx2 inter float32 group. */
SECTIONS
{
  .text.nwgrad ALIGN(4096) :
  {
    KEEP(*(.text.unlikely.nwgrad_placement_shift))""")
for t in TYPES:
    for g in "01":
        for m in "012":
            w(f"    . = ALIGN(4096); *py_exports.cpp.o(.text._Z*BatchEngineI{t}L8GapModel{g}EL9AlignMode{m}E* "
              f".text._Z*AlignerIL8GapModel{g}EL9AlignMode{m}EL9AlignBand?E{t}E*)")
# the standard-library instantiations the engines call per pair (std::vector resize / assign / erase:
# co-hot with the hard path's kernel on nighthaven), apart from the bindings, whose code changes most
w("    . = ALIGN(4096); *py_exports.cpp.o(.text._ZNSt* .text._ZNKSt* .text._ZSt* .text._ZN9__gnu_cxx*)")
w("    . = ALIGN(4096); KEEP(*(.text.nwgrad_placement_shift)) *py_exports.cpp.o(.text._Z*)")
for lv in LEVELS:
    for u in UNITS:
        obj = f"*level_{lv}{u}.cpp.o"
        for t in TYPES:
            grp = "KEEP(*(.text.nwgrad_placement_shift_grp)) " if (lv, u, t) == ("avx2", "_inter", "f") else ""
            off = OFFSET.get((lv, u, t), 0)
            w(f"    . = ALIGN(4096);{f' . += {off};' if off else ''} {grp}{obj}(.text._Z*[a-z_]I{t}[LE]*)")
        w(f"    . = ALIGN(4096); {obj}(.text._Z*)")
w("""    . = ALIGN(4096);
  }
}
INSERT BEFORE .text;""")
print("\n".join(x for x in out if x))
